// Generates prisma/hub/schema.prisma, the location hub's SQLite schema, from the cloud schema.
//
// The hub runs the same application services as the cloud API, so both databases must have the
// same models, fields and enums (src/hub-schema.contract.test.ts compares the generated clients).
// The transform only switches the provider, drops PostgreSQL column types (`@db.*`), removes
// models and enums marked `/// @cloud-only`, and appends the hub-only models.
//
//   node scripts/hub-schema.mjs           write the file
//   node scripts/hub-schema.mjs --check   fail if the committed file is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(resolve(root, 'prisma/schema.prisma'), 'utf8');
const hubModels = readFileSync(resolve(root, 'prisma/hub/hub-models.prisma'), 'utf8');
const target = resolve(root, 'prisma/hub/schema.prisma');

export function toHubSchema(schema, extra) {
  let out = schema;
  // Generator and datasource blocks are replaced wholesale.
  out = out.replace(
    /generator client \{[^}]*\}/,
    [
      'generator client {',
      '  provider = "prisma-client-js"',
      '  output   = "../../generated/hub-client"',
      '}',
    ].join('\n'),
  );
  out = out.replace(
    /datasource db \{[^}]*\}/,
    ['datasource db {', '  provider = "sqlite"', '  url      = env("HUB_DATABASE_URL")', '}'].join(
      '\n',
    ),
  );
  // Cloud-only models and enums: a `/// @cloud-only` line directly above `model X {`/`enum X {`.
  const cloudOnly = /\/\/\/ @cloud-only\n(?:\/\/\/.*\n)*(?:model|enum) (\w+) \{[\s\S]*?\n\}\n?/g;
  const removed = [...out.matchAll(cloudOnly)].map((match) => match[1]);
  out = out.replace(cloudOnly, '').replace(/\n{3,}/g, '\n\n');
  // Relation fields of hub models that point at a removed model: back-relations
  // (`domains TenantDomain[]`) and forward relations with their `@relation(...)` attribute
  // (`organization Organization? @relation(fields: [organizationId], ...)`). The scalar column of
  // a forward relation (`organizationId`) stays, as a plain column.
  for (const name of removed) {
    out = out.replace(
      new RegExp(`\\n {2}\\w+ +${name}(\\[\\]|\\?)?( +@relation\\([^)]*\\))?(?= *\\n)`, 'g'),
      '',
    );
  }
  // A relation in a block of its own leaves an empty block behind.
  out = out.replace(/\n{3,}/g, '\n\n');
  // PostgreSQL native column types have no SQLite equivalent; Prisma's defaults apply.
  out = out.replace(/\s@db\.\w+(\([^)]*\))?/g, '');
  const header = [
    '// GENERATED by scripts/hub-schema.mjs from prisma/schema.prisma — do not edit by hand.',
    '// Location hub (SQLite). Same models as the cloud, plus hub-only models at the end.',
    '',
  ].join('\n');
  return `${header}${out.trimEnd()}\n\n${extra.trimEnd()}\n`;
}

const generated = toHubSchema(source, hubModels);
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== generated) {
    console.error(
      'prisma/hub/schema.prisma is out of date: run `pnpm --filter @pos/database hub:schema`.',
    );
    process.exit(1);
  }
} else {
  writeFileSync(target, generated);
  console.log('wrote prisma/hub/schema.prisma');
}
